# External/generated: doc required only if a repo source ever defines `Sym*`.
const externalSymbols = ["messages.RecordHeader", "connection.TrustAnchorStore"]

func defFile(facadeModule, sym: string): string =
  let key = facadeModule & "." & sym
  if key in relocations:
    return relocations[key]
  if facadeModule == "producer":
    return producerFiles[sym]
  moduleFiles[facadeModule]

func isDefLine(line, sym: string): bool =
  let starred = sym & "*"
  let quoted = "`" & sym & "`*"
  let hasStarred = line.contains(quoted) or line.contains(starred)
  if not hasStarred:
    return false
  if line.contains("proc ") or line.contains("func ") or line.contains("template ") or
      line.contains("macro ") or line.contains("iterator ") or line.contains("type ") or
      line.contains("const ") or line.contains("var ") or line.contains("let "):
    return true
  let s = line.strip()
  let bare =
    s.startsWith(starred) or s.startsWith(quoted) or s == starred or s == quoted
  if not bare:
    return false
  let tag = if s.startsWith(quoted): quoted else: starred
  var rest = s[tag.len .. ^1].strip(leading = true, trailing = false)
  if rest.len == 0:
    return true # `Name* =` alias header; rhs runs on the next lines
  rest[0] in {'=', ':', ',', '('}

func indentOf(line: string): int =
  line.len - line.strip(leading = true, trailing = false).len

func parenBalance(line: string): int =
  line.count({'(', '[', '{'}) - line.count({')', ']', '}'})

func trailingDoc(line: string): bool =
  ## True when `line` carries a `##` after some declaration text on it. A `##`
  ## inside a string or char literal is not a doc comment.
  let at = line.find("##")
  if at < 0:
    return false
  let before = line[0 ..< at]
  if before.strip().len == 0:
    return false
  before.count('"') mod 2 == 0 and before.count('\'') mod 2 == 0

func hasDoc(src: seq[string], defIdx: int): bool =
  if trailingDoc(src[defIdx]):
    return true # (d) doc joined onto a single-line header
  if defIdx > 0 and
      src[defIdx - 1].strip(leading = true, trailing = false).startsWith("##"):
    return true # (a) doc block directly above
  let baseIndent = indentOf(src[defIdx])
  let stripped = src[defIdx].strip()
  var k = defIdx + 1
  if stripped.endsWith("="):
    # Alias rhs (`Name* =`): the declaration runs on the next lines.
    var steps = 0
    while k < src.len and steps < 8:
      let l = src[k]
      if l.strip(leading = true, trailing = false).startsWith("##"):
        return true
      if l.strip() == "" or l.strip(leading = true, trailing = false).startsWith("#"):
        inc k
        inc steps
        continue
      if indentOf(l) <= baseIndent:
        return false
      inc k
      inc steps
    return false
  # Multi-line headers run to their balanced close first.
  var depth = parenBalance(src[defIdx])
  var steps = 0
  while depth > 0 and k < src.len and steps < 40:
    depth += parenBalance(src[k])
    if depth <= 0 and trailingDoc(src[k]):
      return true # (d) doc joined onto the header's closing line
    inc k
    inc steps
  # After the header only blank/non-doc comments may intervene before ##.
  while k < src.len:
    let l = src[k]
    if l.strip() == "":
      inc k
      continue
    if l.strip(leading = true, trailing = false).startsWith("#") and
        not l.strip(leading = true, trailing = false).startsWith("##"):
      inc k
      continue
    return l.strip(leading = true, trailing = false).startsWith("##")
  false

proc facadeEntries(): seq[(string, string)] =
  # Only the single top-level `export` block is the contract; doc comments and
  # imports above it may contain dotted tokens that must not parse as entries.
  var inExport = false
  for line in lines(projectRoot / "async_kafka.nim"):
    let s = line.strip()
    if s == "export":
      inExport = true
      continue
    if not inExport:
      continue
    if s == "" or s.startsWith("#"):
      continue
    for part in s.split(','):
      let p = part.strip().replace("`", "")
      let dot = p.find('.')
      if dot > 0 and p.len > dot + 1 and ' ' notin p and '\t' notin p:
        result.add((p[0 ..< dot].strip(), p[dot + 1 .. ^1].strip()))

proc undocumentedFacadeSymbols(): seq[string] =
  for (facadeModule, sym) in facadeEntries():
    if sym.startsWith("ke"):
      continue # protocol registry; covered by the group-doc test below
    let key = facadeModule & "." & sym
    if key in externalSymbols:
      let path = moduleFiles[facadeModule]
      let src = readFile(projectRoot / path).splitLines()
      var defined = false
      for i, line in src:
        if isDefLine(line, sym):
          defined = true
          if not hasDoc(src, i):
            result.add(key & " (now repo-defined, needs a doc)")
          break
      if not defined:
        discard # still external/generated: exemption holds
      continue
    let path = defFile(facadeModule, sym)
    let src = readFile(projectRoot / path).splitLines()
    var found = false
    var documented = false
    for i, line in src:
      if isDefLine(line, sym):
        found = true
        # Only the first declaration is the one the generator indexes, so a doc
        # on a later one (an implementation behind a forward declaration, say)
        # reaches the generated page as no doc at all.
        documented = hasDoc(src, i)
        break
    if not found:
      result.add(key & " (definition not found in " & path & ")")
    elif not documented:
      result.add(key & " (no doc in " & path & ")")

suite "Public API docs":
  test "every facade symbol carries a doc comment":
    let missing = undocumentedFacadeSymbols()
    if missing.len > 0:
      echo "undocumented facade symbols:"
      for m in missing:
        echo "  ", m
    check missing.len == 0

  test "ke* registry keeps its contract on a symbol the docs render":
    # The `ke*` codes are exempt from per-symbol docs, so the contract has to
    # live on the type, which the generator renders. A `##` directly above a
    # `const` renders as the module description; only a `##` inside the block
    # attaches to no symbol and is dropped silently, which is how the contract
    # went missing from the generated pages before.
    let src = readFile(projectRoot / "async_kafka/errors.nim").splitLines()
    var typeIdx = -1
    for i, line in src:
      if isDefLine(line, "KafkaErrorCode"):
        typeIdx = i
        break
    check typeIdx > 0
    check hasDoc(src, typeIdx)

    var keIdx = -1
    for i, line in src:
      if line.contains("keNone* ="):
        keIdx = i
        break
    check keIdx > 0
    # A `##` block between `const` and the first code is attached to no symbol
    # and is dropped silently, so it would read as covering the codes below it.
    var j = keIdx - 1
    while j >= 0 and src[j].strip() != "const":
      check not src[j].strip(leading = true, trailing = false).startsWith("##")
      dec j
    check j >= 0
    if j > 0:
      check not src[j - 1].strip(leading = true, trailing = false).startsWith("##")
