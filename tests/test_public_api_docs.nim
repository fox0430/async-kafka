## Contract test: every symbol re-exported by the package root module
## carries a `##` doc comment at its definition site.
##
## Accepted doc positions (the only four the checker recognises):
##   (a) a `##` block on the line directly above the definition;
##   (b) a `##` block as the first body line of a proc (the signature's
##       trailing `=` is on the line above it);
##   (c) a `##` line directly after a single-line header (`Foo* = object ...`),
##       allowing multi-line headers to run to their balanced close first;
##   (d) a `##` trailing the header itself (`Foo* = object ## doc`), which is
##       where `nph` joins a lone doc line, so the test must accept it.
## A `##` that shows up later — member docs inside an enum/object — does NOT
## count for the enclosing symbol, but a `##` a few indented body lines down a
## `=`-ending header still counts.
##
## Deliberate exemptions, each with its rationale inline:
##   - `ke*` codes: the protocol registry. Meanings live in the protocol, not
##     in 80 near-identical comments; the `KafkaErrorCode` type doc carries the
##     contract and `kafkaErrorName` renders them (asserted by the second test
##     below, which also rejects a doc the generator would drop).
##   - `connection.TrustAnchorStore`: re-exported from chronos, no repo source.
##   - `messages.RecordHeader`: generated by the schema macro, no repo source.
##     Both are looked up first: if a repo source ever defines `Sym*` for them,
##     the doc requirement applies automatically.

